--  запрет будущей даты, журналы истории.
--
--  Требование: разделы 1–8 основного скрипта должны быть применены,
--  в table_tax_rates должны быть засеяны ставки:
--     ('ФЛ', '2020-01-01', 0.04)
--     ('ЮЛ', '2020-01-01', 0.06)
