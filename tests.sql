-- =========================================================================
-- 10. Финальная сверка: сумма налога должна совпадать с пересчётом "с нуля"
-- =========================================================================

-- Пересчёт ожидаемой суммы по всем НЕ удалённым строкам:
SELECT EXTRACT(YEAR FROM date)::INT                           AS year,
       EXTRACT(MONTH FROM date)::INT                          AS month,
       SUM(income * function_get_tax_rate(person_type, date)) AS expected_tax
FROM table_income
WHERE is_deleted = FALSE
GROUP BY 1, 2
ORDER BY 1, 2;

-- Фактическое содержимое table_taxes:
SELECT year, month, tax AS actual_tax
FROM table_taxes
ORDER BY year, month;

-- Ожидаем совпадение:
-- 2024 | 2 | 180.00
-- 2024 | 3 |  80.00
-- (январь 2024 отсутствует или равен 0 — см. п. 7.1)


-- =========================================================================
-- 11. Проверка журнала изменений доходов
-- =========================================================================

SELECT id,
       income_id,
       operation,
       changed_at,
       old_row ->> 'income' AS old_income,
       new_row ->> 'income' AS new_income
FROM table_income_history
ORDER BY id;
-- Ожидаем последовательность:
--   I (id=1), I (id=2), I (id=3), I (id=4),
--   U (id=1, income 1000→2000),
--   U (id=2, is_deleted),
--   U (id=2, is_deleted),
--   U (id=2, person_type),
--   U (id=2, date),
--   U (id=3, date),
--   U (id=1, is_deleted)

SELECT COUNT(*) AS income_history_rows
FROM table_income_history;
-- Ожидаем: 11


-- =========================================================================
-- 12. Проверка журнала изменений налогов
-- =========================================================================

SELECT id, year, month, delta, income_id
FROM table_taxes_history
ORDER BY id;
-- Ожидаем (сокращённо):
--   +40.00  (2024-01, id=1)
--  +120.00  (2024-01, id=2)
--  +180.00  (2024-02, id=4)
--   +40.00  (2024-01, id=1)      -- изменение income
--  -120.00  (2024-01, id=2)      -- is_deleted=TRUE
--  +120.00  (2024-01, id=2)      -- is_deleted=FALSE
--   -40.00  (2024-01, id=2)      -- person_type ЮЛ→ФЛ
--   -80.00  (2024-01, id=2)      -- перенос из января
--   +80.00  (2024-03, id=2)      -- перенос в март
--   -80.00  (2024-01, id=1)      -- is_deleted=TRUE

SELECT COUNT(*) AS taxes_history_rows
FROM table_taxes_history;
-- Ожидаем: 10


