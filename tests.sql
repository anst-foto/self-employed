-- =========================================================================
-- 0. ОЧИСТКА ПЕРЕД ТЕСТОМ
-- =========================================================================
TRUNCATE table_taxes_history RESTART IDENTITY CASCADE;
TRUNCATE table_income_history RESTART IDENTITY CASCADE;
TRUNCATE table_taxes;
TRUNCATE table_income RESTART IDENTITY CASCADE;


-- =========================================================================
-- 1. INSERT: обычные доходы
-- =========================================================================

-- 1.1 ФЛ, 1000, январь 2024, не удалён → +40.00
INSERT INTO table_income (date, person_type, income)
VALUES ('2024-01-15', 'ФЛ', 1000);

-- 1.2 ЮЛ, 2000, январь 2024, не удалён → +120.00 (итого 160.00)
INSERT INTO table_income (date, person_type, income)
VALUES ('2024-01-20', 'ЮЛ', 2000);

-- 1.3 ФЛ, 500, январь 2024, УДАЛЁН → налог не должен появиться
INSERT INTO table_income (date, person_type, income, is_deleted)
VALUES ('2024-01-25', 'ФЛ', 500, TRUE);

-- 1.4 ЮЛ, 3000, февраль 2024 → +180.00
INSERT INTO table_income (date, person_type, income)
VALUES ('2024-02-10', 'ЮЛ', 3000);

SELECT *
FROM table_taxes
ORDER BY year, month;
-- Ожидаем:
-- year | month |  tax
-- 2024 |   1   | 160.00
-- 2024 |   2   | 180.00


-- =========================================================================
-- 2. UPDATE: изменение дохода (income)
-- =========================================================================

-- 2.1 У строки id=1 меняем доход 1000 → 2000.
-- Ставка ФЛ = 4%. Было 40, стало 80, дельта +40. Январь: 160 + 40 = 200.
UPDATE table_income
SET income = 2000
WHERE id = 1;

SELECT *
FROM table_taxes
ORDER BY year, month;
-- Ожидаем:
-- 2024 | 1 | 200.00
-- 2024 | 2 | 180.00


-- =========================================================================
-- 3. UPDATE: изменение is_deleted (мягкое удаление / восстановление)
-- =========================================================================

-- 3.1 У строки id=2 (ЮЛ, 2000, январь) ставим is_deleted = TRUE.
-- Налог ЮЛ = 6% = 120. Вычитаем. Январь: 200 - 120 = 80.
UPDATE table_income
SET is_deleted = TRUE
WHERE id = 2;

SELECT *
FROM table_taxes
ORDER BY year, month;
-- Ожидаем:
-- 2024 | 1 | 80.00
-- 2024 | 2 | 180.00

-- 3.2 Восстанавливаем строку id=2 (is_deleted = FALSE).
-- Снова начисляем 6% от 2000 = 120. Январь: 80 + 120 = 200.
UPDATE table_income
SET is_deleted = FALSE
WHERE id = 2;

SELECT *
FROM table_taxes
ORDER BY year, month;
-- Ожидаем:
-- 2024 | 1 | 200.00
-- 2024 | 2 | 180.00


-- =========================================================================
-- 4. UPDATE: изменение типа лица (person_type)
-- =========================================================================

-- 4.1 У строки id=2 меняем тип ЮЛ → ФЛ (доход тот же 2000).
-- Было 6% = 120, стало 4% = 80, дельта -40. Январь: 200 - 40 = 160.
UPDATE table_income
SET person_type = 'ФЛ'
WHERE id = 2;

SELECT *
FROM table_taxes
ORDER BY year, month;
-- Ожидаем:
-- 2024 | 1 | 160.00
-- 2024 | 2 | 180.00


-- =========================================================================
-- 5. UPDATE: изменение date (перенос в другой период)
-- =========================================================================

-- 5.1 У строки id=2 (ФЛ, 2000, январь) меняем дату на март 2024.
-- Из января снимаем 4% от 2000 = 80 → январь: 160 - 80 = 80.
-- В март начисляем 80 → март: 0 + 80 = 80.
UPDATE table_income
SET date = '2024-03-05'
WHERE id = 2;

SELECT *
FROM table_taxes
ORDER BY year, month;
-- Ожидаем:
-- 2024 | 1 |  80.00
-- 2024 | 2 | 180.00
-- 2024 | 3 |  80.00


-- =========================================================================
-- 6. UPDATE: изменение date у УДАЛЁННОЙ строки (налога быть не должно)
-- =========================================================================

-- 6.1 У строки id=3 (ФЛ, 500, январь, is_deleted=TRUE) меняем дату на апрель.
-- Строка удалена — ни снятия, ни начисления быть не должно.
UPDATE table_income
SET date = '2024-04-01'
WHERE id = 3;

SELECT *
FROM table_taxes
ORDER BY year, month;
-- Ожидаем: без изменений
-- 2024 | 1 |  80.00
-- 2024 | 2 | 180.00
-- 2024 | 3 |  80.00


-- =========================================================================
-- 7. UPDATE: is_deleted у активной строки
-- =========================================================================

-- 7.1 У строки id=1 (ФЛ, 2000, январь, не удалена) ставим is_deleted=TRUE.
-- Снимаем 4% от 2000 = 80. Январь: 80 - 80 = 0.
UPDATE table_income
SET is_deleted = TRUE
WHERE id = 1;

SELECT *
FROM table_taxes
ORDER BY year, month;
-- Ожидаем:
-- 2024 | 1 |   0.00
-- 2024 | 2 | 180.00
-- 2024 | 3 |  80.00


