-- =========================================================================
-- 10. ФИНАЛЬНАЯ СВЕРКА: СУММА НАЛОГА ДОЛЖНА СОВПАДАТЬ С ПЕРЕСЧЁТОМ
-- =========================================================================

-- 10.1. Пересчёт ожидаемой суммы налога по всем неудалённым записям о доходах.
SELECT EXTRACT(YEAR FROM date)::INT                           AS year,
       EXTRACT(MONTH FROM date)::INT                          AS month,
       SUM(income * function_get_tax_rate(person_type, date)) AS expected_tax
FROM table_income
WHERE is_deleted = FALSE
GROUP BY 1, 2
ORDER BY 1, 2;

-- 10.2. Фактическое содержимое таблицы накопленного налога.
SELECT year, month, tax AS actual_tax
FROM table_taxes
ORDER BY year, month;

-- Ожидаем совпадение результатов запросов 10.1 и 10.2:
--   2024 | 2 | 180.00
--   2024 | 3 |  80.00
-- Январь 2024 может присутствовать со значением 0.00
-- либо отсутствовать — это зависит от того, удалялась ли нулевая строка.


-- =========================================================================
-- 11. ПРОВЕРКА ЖУРНАЛА ИЗМЕНЕНИЙ ДОХОДОВ
-- =========================================================================

-- 11.1. Построчный вывод журнала изменений доходов.
SELECT id,
       income_id,
       operation,
       changed_at,
       old_row ->> 'income' AS old_income,
       new_row ->> 'income' AS new_income
FROM table_income_history
ORDER BY id;

-- Ожидаемая последовательность операций (одиннадцать записей):
--   1)  Вставка записи с идентификатором 1
--   2)  Вставка записи с идентификатором 2
--   3)  Вставка записи с идентификатором 3
--   4)  Вставка записи с идентификатором 4
--   5)  Обновление записи 1: income изменён с 1000 на 2000
--   6)  Обновление записи 2: is_deleted изменён с ЛОЖЬ на ИСТИНА
--   7)  Обновление записи 2: is_deleted изменён с ИСТИНА на ЛОЖЬ
--   8)  Обновление записи 2: person_type изменён с ЮЛ на ФЛ
--   9)  Обновление записи 2: date изменена с января на март
--   10) Обновление записи 3: date изменена с января на апрель
--   11) Обновление записи 1: is_deleted изменён с ЛОЖЬ на ИСТИНА

-- 11.2. Общее количество записей в журнале изменений доходов.
SELECT COUNT(*) AS income_history_rows
FROM table_income_history;
-- Ожидаемый результат: 11


