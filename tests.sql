--
--  Проверяется:
--    - триггер расчёта налога при вставке и обновлении доходов;
--    - триггер запрета жёсткого удаления доходов;
--    - триггер запрета даты дохода в будущем;
--    - журнал изменений записей о доходах;
--    - журнал изменений налогов по периодам.
--
--  Требование:
--    Разделы 1–8 основного скрипта должны быть применены.
--    В таблице table_tax_rates должны присутствовать ставки:
--      ('ФЛ', '2020-01-01', 0.04)
--      ('ЮЛ', '2020-01-01', 0.06)
-- =========================================================================


-- =========================================================================
-- 0. ОЧИСТКА ПЕРЕД ТЕСТОМ
-- =========================================================================
TRUNCATE table_taxes_history RESTART IDENTITY CASCADE;
TRUNCATE table_income_history RESTART IDENTITY CASCADE;
TRUNCATE table_taxes;
TRUNCATE table_income RESTART IDENTITY CASCADE;


-- =========================================================================
-- 1. ВСТАВКА: ОБЫЧНЫЕ ДОХОДЫ
-- =========================================================================

-- 1.1. Физическое лицо, доход 1000, январь 2024, не удалён.
--      Ставка физического лица = 4 процента.
--      Ожидаемое начисление налога: +40.00.
INSERT INTO table_income (date, person_type, income)
VALUES ('2024-01-15', 'ФЛ', 1000);

-- 1.2. Юридическое лицо, доход 2000, январь 2024, не удалён.
--      Ставка юридического лица = 6 процентов.
--      Ожидаемое начисление налога: +120.00.
--      Итого за январь 2024: 160.00.
INSERT INTO table_income (date, person_type, income)
VALUES ('2024-01-20', 'ЮЛ', 2000);

-- 1.3. Физическое лицо, доход 500, январь 2024, помечен как удалённый.
--      Налог начисляться не должен, потому что запись исключена из расчёта.
INSERT INTO table_income (date, person_type, income, is_deleted)
VALUES ('2024-01-25', 'ФЛ', 500, TRUE);

-- 1.4. Юридическое лицо, доход 3000, февраль 2024, не удалён.
--      Ставка юридического лица = 6 процентов.
--      Ожидаемое начисление налога: +180.00.
INSERT INTO table_income (date, person_type, income)
VALUES ('2024-02-10', 'ЮЛ', 3000);

SELECT *
FROM table_taxes
ORDER BY year, month;
-- Ожидаемый результат:
--   year | month |  tax
--   2024 |   1   | 160.00
--   2024 |   2   | 180.00


-- =========================================================================
-- 2. ОБНОВЛЕНИЕ: ИЗМЕНЕНИЕ СУММЫ ДОХОДА
-- =========================================================================

-- 2.1. У записи с идентификатором 1 меняем доход с 1000 на 2000.
--      Ставка физического лица = 4 процента.
--      Было начислено 40.00, стало 80.00, разница +40.00.
--      Итого за январь 2024: 160.00 + 40.00 = 200.00.
UPDATE table_income
SET income = 2000
WHERE id = 1;

SELECT *
FROM table_taxes
ORDER BY year, month;
-- Ожидаемый результат:
--   2024 | 1 | 200.00
--   2024 | 2 | 180.00


-- =========================================================================
-- 3. ОБНОВЛЕНИЕ: ИЗМЕНЕНИЕ ПРИЗНАКА УДАЛЕНИЯ
-- =========================================================================

-- 3.1. У записи с идентификатором 2 (юридическое лицо, доход 2000, январь 2024)
--      устанавливаем признак удаления в значение ИСТИНА.
--      Ставка юридического лица = 6 процентов, начисленный налог 120.00.
--      Вычитаем: январь 2024, 200.00 - 120.00 = 80.00.
UPDATE table_income
SET is_deleted = TRUE
WHERE id = 2;

SELECT *
FROM table_taxes
ORDER BY year, month;
-- Ожидаемый результат:
--   2024 | 1 |  80.00
--   2024 | 2 | 180.00

-- 3.2. Восстанавливаем запись с идентификатором 2: признак удаления = ЛОЖЬ.
--      Снова начисляем 6 процентов от 2000 = 120.00.
--      Январь 2024: 80.00 + 120.00 = 200.00.
UPDATE table_income
SET is_deleted = FALSE
WHERE id = 2;

SELECT *
FROM table_taxes
ORDER BY year, month;
-- Ожидаемый результат:
--   2024 | 1 | 200.00
--   2024 | 2 | 180.00


-- =========================================================================
-- 4. ОБНОВЛЕНИЕ: ИЗМЕНЕНИЕ ТИПА ЛИЦА
-- =========================================================================

-- 4.1. У записи с идентификатором 2 меняем тип лица
--      с юридического на физическое. Доход остаётся 2000.
--      Было 6 процентов = 120.00, стало 4 процента = 80.00, разница -40.00.
--      Январь 2024: 200.00 - 40.00 = 160.00.
UPDATE table_income
SET person_type = 'ФЛ'
WHERE id = 2;

SELECT *
FROM table_taxes
ORDER BY year, month;
-- Ожидаемый результат:
--   2024 | 1 | 160.00
--   2024 | 2 | 180.00


-- =========================================================================
-- 5. ОБНОВЛЕНИЕ: ИЗМЕНЕНИЕ ДАТЫ ДОХОДА (ПЕРЕНОС В ДРУГОЙ ПЕРИОД)
-- =========================================================================

-- 5.1. У записи с идентификатором 2 (физическое лицо, доход 2000, январь 2024)
--      меняем дату на 5 марта 2024.
--      Из января снимаем 4 процента от 2000 = 80.00.
--      Январь 2024: 160.00 - 80.00 = 80.00.
--      В март начисляем 80.00.
--      Март 2024: 0.00 + 80.00 = 80.00.
UPDATE table_income
SET date = '2024-03-05'
WHERE id = 2;

SELECT *
FROM table_taxes
ORDER BY year, month;
-- Ожидаемый результат:
--   2024 | 1 |  80.00
--   2024 | 2 | 180.00
--   2024 | 3 |  80.00


-- =========================================================================
-- 6. ОБНОВЛЕНИЕ ДАТЫ У УДАЛЁННОЙ ЗАПИСИ
-- =========================================================================

-- 6.1. У записи с идентификатором 3
--      (физическое лицо, доход 500, январь 2024, признак удаления = ИСТИНА)
--      меняем дату на 1 апреля 2024.
--      Запись помечена как удалённая, поэтому ни снятие, ни начисление
--      налога происходить не должно.
UPDATE table_income
SET date = '2024-04-01'
WHERE id = 3;

SELECT *
FROM table_taxes
ORDER BY year, month;
-- Ожидаемый результат (без изменений по сравнению с предыдущим шагом):
--   2024 | 1 |  80.00
--   2024 | 2 | 180.00
--   2024 | 3 |  80.00


-- =========================================================================
-- 7. ОБНОВЛЕНИЕ ПРИЗНАКА УДАЛЕНИЯ У АКТИВНОЙ ЗАПИСИ
-- =========================================================================

-- 7.1. У записи с идентификатором 1
--      (физическое лицо, доход 2000, январь 2024, не удалена)
--      устанавливаем признак удаления в значение ИСТИНА.
--      Снимаем 4 процента от 2000 = 80.00.
--      Январь 2024: 80.00 - 80.00 = 0.00.
UPDATE table_income
SET is_deleted = TRUE
WHERE id = 1;

SELECT *
FROM table_taxes
ORDER BY year, month;
-- Ожидаемый результат:
--   2024 | 1 |   0.00
--   2024 | 2 | 180.00
--   2024 | 3 |  80.00


-- =========================================================================
-- 8. ПРОВЕРКА ЗАПРЕТА ЖЁСТКОГО УДАЛЕНИЯ ДОХОДОВ
